#!/usr/bin/env node
// Makes the 20 Kliner beta codes, KLNR-XXXX-XXXX, from a crypto-random source.
//
//   beta-codes.local.txt  the plaintext codes, one per line, for the owner to
//                         hand out. Private: it is in .gitignore.
//   beta-codes.sql        INSERT OR IGNORE of the sha256 hex of each normalised
//                         code (uppercase, no spaces, no dashes), for D1.
//
// An existing beta-codes.local.txt is never overwritten: its codes are reused
// and only beta-codes.sql is rebuilt. Delete the .txt yourself to start over.
//
// Run: node gen-codes.mjs

import { createHash, randomInt } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ALPHABET = "ABCDEFGHJKMNPQRSTVWXYZ23456789"; // no I, L, O, U, 0, 1: nothing to misread
const COUNT = 20;
const FORMAT = new RegExp(`^KLNR-[${ALPHABET}]{4}-[${ALPHABET}]{4}$`);

const here = dirname(fileURLToPath(import.meta.url));
const txtPath = join(here, "beta-codes.local.txt");
const sqlPath = join(here, "beta-codes.sql");

// randomInt draws without modulo bias.
function group() {
  let s = "";
  for (let i = 0; i < 4; i++) s += ALPHABET[randomInt(ALPHABET.length)];
  return s;
}

// Must match the Worker: uppercase, spaces and dashes removed.
function normalise(code) {
  return code.toUpperCase().replace(/[\s\-‐-―−]/g, "");
}

function sha256Hex(text) {
  return createHash("sha256").update(text, "utf8").digest("hex");
}

let codes;
if (existsSync(txtPath)) {
  codes = readFileSync(txtPath, "utf8")
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith("#"));
  console.log(`beta-codes.local.txt already exists, so it was left alone: reusing its ${codes.length} codes.`);
  const odd = codes.filter((c) => !FORMAT.test(c));
  if (odd.length) console.log(`Note: ${odd.length} line(s) do not look like KLNR-XXXX-XXXX; they are included anyway: ${odd.join(", ")}`);
  if (!codes.length) {
    console.error("beta-codes.local.txt has no codes in it. Delete the file and run this again to make new ones.");
    process.exit(1);
  }
} else {
  const unique = new Set();
  while (unique.size < COUNT) unique.add(`KLNR-${group()}-${group()}`);
  codes = [...unique];
  writeFileSync(txtPath, codes.join("\n") + "\n", { mode: 0o600 });
  console.log(`Wrote ${COUNT} new codes to beta-codes.local.txt (keep it private).`);
}

const hashes = [...new Set(codes.map((c) => sha256Hex(normalise(c))))];
const sql =
  "-- Generated by gen-codes.mjs: sha256 of each normalised beta code (uppercase, no spaces or dashes).\n" +
  "-- The hashes are unsalted and the codes are short, so treat this file as private too.\n" +
  hashes.map((h) => `INSERT OR IGNORE INTO beta_codes (hash) VALUES ('${h}');`).join("\n") +
  "\n";
writeFileSync(sqlPath, sql, { mode: 0o600 });
console.log(`Wrote beta-codes.sql with ${hashes.length} hashes.`);
console.log("Apply it with: npx wrangler d1 execute kliner --remote --file beta-codes.sql (deploy.sh does this for you).");
